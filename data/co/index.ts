import type { CoAnswer, CoSeriesInput } from "./types";

const q = (
  transcription: string,
  prompt: string,
  options: [string, string, string, string],
  correct: CoAnswer,
  explanation: string,
) => ({ transcription, prompt, options, correct, explanation });

function series(
  slug: string,
  title: string,
  level: string,
  order: number,
  description: string,
  questions: ReturnType<typeof q>[],
): CoSeriesInput {
  return { slug, title, level, order, description, listenings: 1, questions };
}

